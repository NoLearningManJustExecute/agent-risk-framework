"""Evasion inputs: run payload mutations and attack variants live, in both arms.

Detection research Phase 4 asks how far detections hold up when the attack is varied. Mutating
the text of a captured trace would leave its tool sequence unchanged, so every input here runs
live against the model and is labeled by a deterministic oracle:

- `-Mnn` payload mutations of a scenario: generated by the detection research repository, which
  holds the mutation tooling and picks the scenarios. This module only validates and runs them.
- `-Vnn` attack variants: authored in `data/evasion/attack_variants.json`, each pursuing a class's
  objective by another route, scored by its own oracle.

See docs/evasion_inputs.md.

CLI:

    python -m agent_risk_framework.attacks.evasion run --db runs/evasion.db --mutated <file>
"""

from __future__ import annotations

import argparse
from collections.abc import Sequence
from pathlib import Path

from .scenarios import AttackScenario, load_attack_variants, load_catalog, load_mutated, load_seeded
from .seeding import SEEDED_PATH

ATTACK_VARIANTS_PATH = Path("data/evasion/attack_variants.json")
ARMS: tuple[str, ...] = ("baseline", "combined")


def load_evasion(
    mutated: Path | str,
    attack_variants: Path | str = ATTACK_VARIANTS_PATH,
    scenarios: Path | str = "data/attack_scenarios.json",
    seeded: Path | str = SEEDED_PATH,
) -> tuple[AttackScenario, ...]:
    """The mutated scenarios, then the attack variants, each validated against its catalog."""
    catalog = load_catalog(scenarios)
    parents = (*catalog.scenarios, *load_seeded(seeded, catalog))
    return (*load_mutated(mutated, parents), *load_attack_variants(attack_variants, catalog))


def main(argv: Sequence[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description="Run the evasion inputs live.")
    sub = parser.add_subparsers(dest="command", required=True)
    run = sub.add_parser("run", help="run every evasion input live, baseline and combined")
    run.add_argument("--db", required=True)
    run.add_argument("--mutated", required=True, help="the -Mnn scenario file")
    run.add_argument("--manifest", default="configs/experiments/phase4_evasion.yaml")
    run.add_argument("--arm", choices=ARMS, action="append", help="default: both")
    args = parser.parse_args(argv)
    _run(Path(args.db), Path(args.manifest), Path(args.mutated), tuple(args.arm or ARMS))


def _run(db: Path, manifest_path: Path, mutated: Path, arms: Sequence[str]) -> None:
    import anyio

    from ..manifest import load_manifest
    from ..runlog import RunLog
    from .runner import _build_model, run_experiment

    manifest = load_manifest(manifest_path)
    inputs = load_evasion(mutated, scenarios=manifest.attack_set)
    model = _build_model(manifest.model, manifest.provider)
    db.parent.mkdir(parents=True, exist_ok=True)
    with RunLog(db) as log:
        for arm in arms:
            anyio.run(
                lambda arm=arm: run_experiment(
                    model=model,
                    run_log=log,
                    scenarios=inputs,
                    tasks=[],
                    experiment_id=f"{manifest.experiment_id}-{arm}",
                    runs=manifest.runs,
                    seed=manifest.seed,
                    temperature=manifest.temperature,
                    config=arm,
                    progress=lambda r, arm=arm: print(
                        f"{arm} {r.case_id} {r.run_index} {r.outcome.value}", flush=True
                    ),
                )
            )


if __name__ == "__main__":
    main()
